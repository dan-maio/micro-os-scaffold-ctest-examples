// 01 - Runtime: what a board must provide to run µTest++ tests, checked on
// the target. The scaffolder checked the same rules in the sources before
// adding µTest++ to this board (scaffold.json, microTestPlus.boards); this
// suite checks that they hold in the running image.
//
//   - the boot code ran the static constructors, in init_priority order,
//     after the heap was set up (a constructor may allocate);
//   - malloc, new and calloc work, inside the linker script's heap
//     (_Heap_Begin .. _Heap_Limit);
//   - sbrk agrees with it: its break lies inside that region, and it cannot
//     grow past _Heap_Limit.
// GENERATED by micro-os-scaffold (--micro-test-plus).
#include <mtp_board.hpp>

#include <cerrno>
#include <cstdint>
#include <cstdio>
#include <cstdlib>
#include <cstring>
#include <limits>
#include <unistd.h>
#include <vector>

#if !defined(MTP_HOSTED)
extern "C"
{
  extern char _Heap_Begin; // the linker script's heap region
  extern char _Heap_Limit;
}
#endif

namespace
{
  int g_data_word = 0x1234;
  std::uint32_t g_bss_words[32];

  struct probe
  {
    int value;
    probe () : value (0xC0FFEE)
    {
    }
  };
  probe g_probe;

  int g_constructed = 0;
  struct ordered
  {
    int sequence;
    ordered () : sequence (++g_constructed)
    {
    }
  };
  __attribute__ ((init_priority (300))) ordered g_late;
  __attribute__ ((init_priority (200))) ordered g_early;

  // On the host the kernel replaces the C++ memory resource after the
  // static constructors ran, so a vector allocated here could not be
  // deallocated by the suite; the check is meaningful on the boards only.
#if !defined(MTP_HOSTED)
  std::vector<int>* g_by_constructor = new std::vector<int> (32, 7);
#endif

  bool
  in_heap ([[maybe_unused]] const void* p) noexcept
  {
#if defined(MTP_HOSTED)
    return true; // the host's allocator: no linker heap to compare with
#else
    const auto* c = static_cast<const char*> (p);
    return c >= &_Heap_Begin && c < &_Heap_Limit;
#endif
  }
} // namespace

// Registers itself with the runner of this image; see suite-basics.cpp.
mt::static_suite suite_runtime{
  "01 - Runtime", mtp_board::runner (), [] (mt::suite& ts) {
  ts.test (".data and .bss", [] (auto& t) {
    t.expect (mt::eq (g_data_word, 0x1234)) << ".data initialised";
    std::uint32_t any = 0;
    for (const auto word : g_bss_words)
      {
        any |= word;
      }
    t.expect (mt::eq (any, 0u)) << ".bss zero";
  });

  ts.test ("the boot code ran the static constructors", [] (auto& t) {
    t.expect (mt::eq (g_probe.value, 0xC0FFEE)) << "a global object built";
    t.expect (mt::eq (g_constructed, 2)) << "both ordered objects built";
    t.expect (mt::lt (g_early.sequence, g_late.sequence)) << "in init_priority order";
#if !defined(MTP_HOSTED)
    t.expect (mt::ne (static_cast<void*> (g_by_constructor), nullptr))
        << "a constructor could allocate (the heap was set up before them)";
    t.expect (in_heap (g_by_constructor->data ())) << "inside the heap region";
    delete g_by_constructor;
    g_by_constructor = nullptr;
#endif
  });

  ts.test ("malloc, new and calloc inside the linker's heap", [] (auto& t) {
    void* a = std::malloc (100);
    auto* b = new int[100];
    auto* c = static_cast<std::uint8_t*> (std::calloc (64, 1));
    t.expect (mt::all_of (mt::ne (a, nullptr), mt::ne (static_cast<void*> (b), nullptr),
                          mt::ne (static_cast<void*> (c), nullptr)))
        << "all three allocated";
    t.expect (mt::all_of (in_heap (a), in_heap (b), in_heap (c))) << "inside the heap region";
    unsigned zero = 0;
    for (int i = 0; i < 64; ++i)
      {
        zero |= c[i];
      }
    t.expect (mt::eq (zero, 0u)) << "calloc zeroed";
    std::free (a);
    delete[] b;
    std::free (c);
  });

#if !defined(MTP_HOSTED)
  ts.test ("a quarter of the heap, in four blocks", [] (auto& t) {
    const auto heap = static_cast<std::size_t> (&_Heap_Limit - &_Heap_Begin);
    const std::size_t each = heap / 16;
    void* blocks[4] = {};
    int good = 0;
    for (auto& block : blocks)
      {
        block = std::malloc (each);
        if (block != nullptr && in_heap (block)
            && in_heap (static_cast<char*> (block) + each - 1))
          {
            std::memset (block, 0x5a, each);
            ++good;
          }
      }
    char what[64];
    std::snprintf (what, sizeof (what), "4 x %u bytes of a %u-byte heap",
                   static_cast<unsigned> (each), static_cast<unsigned> (heap));
    t.expect (mt::eq (good, 4)) << what;
    for (auto* block : blocks)
      {
        std::free (block);
      }
  });

  ts.test ("sbrk agrees with the linker's heap", [] (auto& t) {
    void* top = sbrk (0);
    const auto* p = static_cast<const char*> (top);
    t.expect (mt::ne (top, reinterpret_cast<void*> (-1))) << "sbrk (0) answers";
    // Compare addresses as integers: µTest++ compares a const char* as a
    // C string, which would walk the heap looking for a terminator.
    const auto at = reinterpret_cast<std::uintptr_t> (p);
    t.expect (mt::all_of (
        mt::ge (at, reinterpret_cast<std::uintptr_t> (&_Heap_Begin)),
        mt::le (at, reinterpret_cast<std::uintptr_t> (&_Heap_Limit))))
        << "its break lies inside _Heap_Begin .. _Heap_Limit";
    errno = 0;
    const auto remaining = static_cast<std::size_t> (&_Heap_Limit - p);
    const auto max_diff = static_cast<std::size_t> (
        std::numeric_limits<std::ptrdiff_t>::max () - 4096);
    const auto past = static_cast<std::ptrdiff_t> (
        (remaining <= max_diff ? remaining : max_diff) + 4096);
    t.expect (mt::eq (sbrk (past), reinterpret_cast<void*> (-1)))
        << "it cannot grow past _Heap_Limit";
    t.expect (mt::eq (sbrk (0), top)) << "and a refused request moves nothing";
  });
#endif
  }
};
